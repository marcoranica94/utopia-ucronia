import { readFile, writeFile } from "node:fs/promises";
import { writeJson } from "./recovery/core.ts";

/**
 * S7 coverage: one outcome for every recovered PDF and for every file inside
 * every zip, from the inventory, the proposal reports, the holds and the
 * converted edition. Writes reports/attachments-coverage.json and .md.
 */
type Row = { file: string; outcome: string; detail?: string };
const read = async (file: string) => JSON.parse(await readFile(file, "utf8"));
const inventory = await read("reports/attachments-inventory.json");
const pdfReport = await read("reports/attachments-proposals.json");
const zipReport = await read("reports/attachments-zip-proposals.json");
const conversion = (await read("reports/conversion.json")) as {
  path: string;
  title: string;
  sources: { url: string; entry?: string }[];
}[];
const map = await read("data/map.yaml");
const byUrl = new Map<string, { path: string; title: string }>();
for (const c of conversion)
  for (const s of c.sources)
    byUrl.set(`${s.url.toLowerCase()}::${s.entry ?? ""}`, c);
const urlOf = new Map<string, string>(
  map.documents.map((d: { path: string; url: string }) => [d.path, d.url]),
);
const published = (path: string, entry = "") =>
  byUrl.get(`${(urlOf.get(path) ?? "").toLowerCase()}::${entry}`);

const rows: Row[] = [];
const pdfOutcome = new Map<string, { outcome: string; duplicateOf?: string }>(
  pdfReport.pdfs.map(
    (p: { path: string; outcome: string; duplicateOf?: string }) => [p.path, p],
  ),
);
for (const pdf of inventory.pdfs as { path: string }[]) {
  const edition = published(pdf.path);
  const report = pdfOutcome.get(pdf.path);
  rows.push(
    edition
      ? { file: pdf.path, outcome: "published", detail: edition.path }
      : report?.outcome.startsWith("download")
        ? {
            file: pdf.path,
            outcome: "merged: download copy of a published page",
            detail: report.duplicateOf,
          }
        : report?.outcome.startsWith("scan")
          ? { file: pdf.path, outcome: "scan: OCR pending" }
          : {
              file: pdf.path,
              outcome: "held: fails the text-layer check",
              detail: report?.outcome,
            },
  );
}
const zipOutcome = new Map<string, string>(
  zipReport.files.map(
    (f: { path: string; entry?: string; outcome: string }) => [
      `${f.path}::${f.entry ?? ""}`,
      f.outcome,
    ],
  ),
);
for (const zip of inventory.zips as {
  path: string;
  files: { name: string }[];
}[])
  for (const file of zip.files) {
    const name = `${zip.path} › ${file.name}`;
    const edition = published(zip.path, file.name);
    const outcome = zipOutcome.get(`${zip.path}::${file.name}`) ?? "";
    rows.push(
      edition
        ? { file: name, outcome: "published", detail: edition.path }
        : outcome.startsWith("illustration")
          ? { file: name, outcome: "illustration of the PDF beside it" }
          : outcome.startsWith("scan")
            ? { file: name, outcome: "scan: OCR pending" }
            : outcome.startsWith("not read")
              ? {
                  file: name,
                  outcome: "discarded: presentation or spreadsheet",
                  detail: "kept in the archive",
                }
              : outcome.startsWith("download")
                ? {
                    file: name,
                    outcome: "merged: download copy of a published page",
                    detail: outcome.split(": ").pop(),
                  }
                : {
                    file: name,
                    outcome: "held: fails the text-layer check",
                    detail: outcome,
                  },
    );
  }
const totals: Record<string, number> = {};
for (const row of rows) totals[row.outcome] = (totals[row.outcome] ?? 0) + 1;
if (rows.some((row) => !row.outcome)) throw new Error("A file has no outcome");
await writeJson("reports/attachments-coverage.json", {
  date: new Date().toISOString().slice(0, 10),
  files: rows.length,
  totals,
  rows,
});
const lines = [
  "# Attachments coverage (S7)",
  "",
  `Every recovered PDF and every file inside a zip, ${rows.length} in all, with its outcome. Generated by \`pnpm attachments coverage\`.`,
  "",
  "| Outcome | Files |",
  "| --- | ---: |",
  ...Object.entries(totals)
    .sort(([, a], [, b]) => b - a)
    .map(([k, v]) => `| ${k} | ${v} |`),
  "",
  "## Not published",
  "",
  "| File | Outcome | Detail |",
  "| --- | --- | --- |",
  ...rows
    .filter((r) => r.outcome !== "published")
    .map((r) => `| ${r.file} | ${r.outcome} | ${r.detail ?? ""} |`),
  "",
];
await writeFile("reports/attachments-coverage.md", lines.join("\n"));
