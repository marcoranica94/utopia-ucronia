/**
 * S7, step 1: every recovered PDF with a text layer becomes a work proposal
 * in data/map.yaml, replacing its "attachment" proposal. Owner proposals are
 * never touched. The map is edited line by line (it is regenerated by no one:
 * `editorial:map` refuses to rewrite reviewed proposals), so every other line
 * stays byte-identical.
 *
 * Title and authors come, in order, from the original works catalog entry
 * that links the PDF, from the text of the link on the page that cites it,
 * or from the PDF itself. A PDF whose text is already contained in the page
 * that links to it is a download copy of a published work: it is not
 * proposed, and the report says so.
 */

type Inventory = {
  pdfs: {
    path: string;
    kind?: string;
    linkedFrom: string[];
  }[];
  zips: {
    path: string;
    linkedFrom: string[];
    files?: { name: string; kind?: string }[];
  }[];
};
// `propose --zips`: only the files inside zips (the loose PDFs are done).
const zipsOnly = process.argv.includes("--zips");
type Browse = {
  entries: { title: string; authors: string[]; targets: string[] }[];
  targets: { id: string; source?: string; status: string }[];
};

const inventory = JSON.parse(
  await readFile("reports/attachments-inventory.json", "utf8"),
) as Inventory;
const browse = JSON.parse(
  await readFile("src/generated/browse.json", "utf8"),
) as Browse;
const text = await readFile("data/map.yaml", "utf8");
const map = mapSchema.parse(JSON.parse(text)) as EditorialMap;
const byPath = new Map(map.documents.map((d) => [d.path, d]));

// Catalog: the entry whose targets include the PDF.
const targetSource = new Map(
  browse.targets.filter((t) => t.source).map((t) => [t.id, t.source ?? ""]),
);
const catalog = new Map<string, { title: string; authors: string[] }>();
for (const entry of browse.entries)
  for (const id of entry.targets) {
    const source = targetSource.get(id);
    if (!source || !/\.(?:pdf|zip)$/i.test(source)) continue;
    let key: string;
    try {
      key = urlKey(source);
    } catch {
      continue;
    }
    if (!catalog.has(key)) catalog.set(key, entry);
  }

// Link words that say how to get the file, not what it is.
const GENERIC =
  /\b(?:qui|qua|clicca\w*|click|scaric\w*|download|pdf|file|link|leggi|apri|vai|here|versione|formato|documento|risposta|indirizzo|schema)\b/i;
/** "IL SACRARIO DELLE SABBIE" → "Il sacrario delle sabbie": all-capital
 * titles are a display style of the old pages, not part of the title. */
const sentenceCase = (title: string, body: string) => {
  if (/\p{Ll}/u.test(title)) return title;
  // Proper names keep their capital when the text writes them that way.
  const capital = (word: string) => {
    const lower = word.toLocaleLowerCase("it");
    const upper = lower.charAt(0).toLocaleUpperCase("it") + lower.slice(1);
    const count = (w: string) =>
      body.split(new RegExp(`(?<![\\p{L}])${w}(?![\\p{L}])`, "u")).length - 1;
    return count(upper) > count(lower) ? upper : lower;
  };
  const words = title.split(/(\p{L}+)/u);
  return words
    .map((part) => (/\p{L}/u.test(part) ? capital(part) : part))
    .join("")
    .replace(/^(\P{L}*)(\p{L})/u, (_m, a, b) => a + b.toLocaleUpperCase("it"));
};
// Titles read from the text where no catalog entry, link or heading names
// the work (checked by hand, 19/11/2026); each quotes the PDF or its file.
const TITLE_FROM_TEXT: Record<string, string> = {
  // "Il piano originale dell'Operazione Leone Marino" (index and introduction)
  "utopiaucronia/dipinti_sandro/matteo_bosso_leone_marino.pdf":
    "Operazione Leone Marino",
  // Both open with the section "Dinastia Giulio-Claudia"; file names differ.
  "utopiaucronia/magellania/canale_di_augusto_2020.pdf":
    "Canale di Augusto 2020",
  "utopiaucronia/valentino/dinastie_canale.pdf": "Dinastie del Canale",
  // First line: "Quindici livelli di appartenenza sociale in indoeuropeo
  // preistorico ricostruito dalla comparazione fra celtico, germanico, …"
  "utopiaucronia/dante33/clanna.pdf":
    "Quindici livelli di appartenenza sociale in indoeuropeo preistorico",
  // First line: "L'Uomo che potè essere Re. Premessa: …"
  "utopiaucronia/dante33/uomo_che_pote_essere_re.pdf":
    "L'Uomo che potè essere Re",
  "utopiaucronia/900_toponimi_indoeuropei.pdf": "900 toponimi indoeuropei",
};
// Files inside zips whose link and name say nothing (checked by hand,
// 19/11/2026).
const ZIP_TITLES: Record<string, string> = {
  // Link text "La sua stesura"; the PDF's metadata title.
  "utopiaucronia/confederacy_history.zip::Confederacy_history.pdf":
    "Confederacy, history of",
  // A table of the Corpo Aereo Italiano; the file is named "CAI".
  "utopiaucronia/ii_gm_hdosbe_files.zip::II_GM_hdosbe_files/CAI.pdf": "CAI",
};
/** A usable title has two words with letters and is not a placeholder. */
const usable = (t: string) =>
  (t.match(/\p{L}{2,}/gu) ?? []).length >= 2 &&
  !/^(?:indice|index|sommario|contents?|normal\w*)\b/i.test(t) &&
  !/^[\p{L}]+[A-Z][\p{L}]+$/u.test(t);
const plain = (html: string) => {
  const $ = load(html);
  $("script,style,noscript").remove();
  return $("body").text().replace(/\s+/g, " ").trim();
};
const shingles = (s: string, n = 8) => {
  const words = s
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim()
    .split(" ");
  const out = new Set<string>();
  for (let i = 0; i + n <= words.length; i++)
    out.add(words.slice(i, i + n).join(" "));
  return out;
};
const language = (body: string) => {
  const sample = body.slice(0, 12000).toLowerCase();
  const words = {
    it: /\b(?:della|delle|degli|gli|che|nella|anche|sono|questo)\b/g,
    fr: /\b(?:les|des|une|dans|pour|avec|sont|cette|mais)\b/g,
    es: /\b(?:los|las|una|del|para|como|pero|esta|con)\b/g,
    en: /\b(?:the|with|from|this|which|would|their|were)\b/g,
  };
  const ranking = Object.entries(words)
    .map(([lang, re]) => ({ lang, count: [...sample.matchAll(re)].length }))
    .sort((a, b) => b.count - a.count);
  const value =
    ranking[0].count >= 5 && ranking[0].count > ranking[1].count * 1.3
      ? (ranking[0].lang as "it" | "fr" | "es" | "en")
      : ("unknown" as const);
  return {
    value,
    review: proposed(
      value === "unknown"
        ? "Insufficient language evidence; do not silently label the text Italian."
        : "Proposed from the text layer's function words; not an owner-approved attribution.",
      body.slice(0, 220),
    ),
  };
};

/** The text of the link that cites a document, and the citing page that
 * already contains its text (then it is a download copy of that page). */
async function referrers(
  document: { url: string },
  linkedFrom: string[],
  body: string,
) {
  let linkText: string | undefined;
  let duplicate: { path: string; containment: number } | undefined;
  const own = shingles(body);
  for (const referrer of linkedFrom) {
    const page = byPath.get(referrer);
    if (!page) continue;
    const html = decode(await readFile(safePath("archive/original", referrer)));
    const $ = load(html);
    $("a[href]").each((_i, a) => {
      if (linkText) return;
      try {
        if (
          urlKey(new URL($(a).attr("href") ?? "", page.url).href) !==
          urlKey(document.url)
        )
          return;
      } catch {
        return;
      }
      const t = redact($(a).text());
      if (t.length < 4 || GENERIC.test(t) || t === "[email removed]") return;
      // "Parte Prima (55 a.C. - 476 d.C.)": a part takes its series' name.
      const quoted = /^["“«](.+?)["”»]/.exec(t)?.[1];
      linkText = /^(?:parte|part|capitolo|volume|vol\.)\b/i.test(t)
        ? `${redact($("title").first().text()).replace(/^\[[^\]]*\]\s*/, "") || "Parte"}: ${t}`
        : (quoted ?? t).trim();
    });
    if (own.size >= 20) {
      const theirs = shingles(plain(html));
      let shared = 0;
      for (const s of own) if (theirs.has(s)) shared++;
      const containment = shared / own.size;
      if (
        containment >= 0.6 &&
        (!duplicate || containment > duplicate.containment)
      )
        duplicate = { path: referrer, containment };
    }
  }
  return { linkText, duplicate };
}

const lineOf = new Map<string, number>();
const lines = text.split("\n");
for (const [i, line] of lines.entries()) {
  const id = /^\s*\{"id":"([^"]+)"/.exec(line)?.[1];
  if (id) lineOf.set(id, i);
}

const newItems: EditorialItem[] = [];
const authorDocs = new Map<string, { name: string; docs: Set<string> }>();
const report: {
  path: string;
  outcome: string;
  title?: string;
  titleFrom?: string;
  authors?: string[];
  duplicateOf?: string;
  containment?: number;
}[] = [];

for (const pdf of zipsOnly ? [] : inventory.pdfs) {
  const document = byPath.get(pdf.path);
  if (!document) throw new Error(`PDF missing from the map: ${pdf.path}`);
  const proposal = map.proposals.find(
    (p) => p.id === `proposal-${document.id}`,
  );
  if (!proposal) throw new Error(`No proposal for ${pdf.path}`);
  if (proposal.review.by === "owner" || proposal.action !== "attachment") {
    report.push({ path: pdf.path, outcome: `kept (${proposal.action})` });
    continue;
  }
  if (pdf.kind === "scan" || pdf.kind === "mixed") {
    report.push({ path: pdf.path, outcome: "scan: OCR pending" });
    continue;
  }
  const bytes = await readFile(safePath("archive/original", pdf.path));
  const edition = await pdfEdition(bytes);
  if (!edition) throw new Error("unpdf unavailable");
  const body = plain(edition.html);

  // Referring pages: link text, and whether they already hold this text.
  const { linkText, duplicate } = await referrers(
    document,
    pdf.linkedFrom,
    body,
  );
  if (duplicate) {
    report.push({
      path: pdf.path,
      outcome: "download copy of a page",
      duplicateOf: duplicate.path,
      containment: Math.round(duplicate.containment * 100) / 100,
    });
    continue;
  }

  const entry = catalog.get(urlKey(document.url));
  // From the PDF: its first heading, its metadata title, its file name.
  const heading = redact(load(edition.html)("h2").first().text());
  const metadata = redact(
    load(edition.html)("title").text().replace(/_/g, " "),
  );
  const filename = (pdf.path.split("/").pop() ?? "")
    .replace(/\.pdf$/i, "")
    .replace(/[_\s]+/g, " ")
    .trim();
  const fromPdf =
    [heading, metadata, filename].find((t) => usable(t) && t.length <= 120) ??
    filename;
  const [rawTitle, titleFrom] = entry
    ? [redact(entry.title), "catalog"]
    : linkText
      ? [linkText, "link"]
      : TITLE_FROM_TEXT[pdf.path]
        ? [TITLE_FROM_TEXT[pdf.path], "text"]
        : [fromPdf, "pdf"];
  const cased = sentenceCase(rawTitle, body);
  const title = cased.charAt(0).toLocaleUpperCase("it") + cased.slice(1);
  const authors = (entry?.authors ?? [])
    .map((name) => redact(name))
    .filter((name) => name && name !== "[email removed]");
  for (const name of authors) {
    const id = authorId(name);
    if (!authorDocs.has(id)) authorDocs.set(id, { name, docs: new Set() });
    authorDocs.get(id)?.docs.add(document.id);
  }
  const quote = body.slice(0, 220);
  const item: EditorialItem = {
    id: itemId(document.url),
    slug: itemSlug(title, document.url),
    title,
    level: "work",
    authors: authors.map(authorId),
    language: language(body),
    sources: [
      {
        documentId: document.id,
        url: document.url,
        ...(document.timestamp ? { timestamp: document.timestamp } : {}),
        selection: { kind: "whole" },
      },
    ],
    classification: unknownClassification(quote),
    contributions: [],
    developedIn: [],
    composition: "single",
    review: proposed(
      `A recovered PDF with a text layer, read as text like the HTML works (S7); title from the ${titleFrom === "catalog" ? "original works catalog" : titleFrom === "link" ? "link that cites it" : titleFrom === "text" ? "opening of the text" : "PDF itself"}.`,
      quote,
    ),
  };
  newItems.push(item);
  lines[lineOf.get(proposal.id) ?? -1] = lines[
    lineOf.get(proposal.id) ?? -1
  ].replace(
    /\{.*\}/,
    JSON.stringify({
      id: proposal.id,
      documents: proposal.documents,
      action: "work",
      level: "work",
      targets: [item.id],
      review: item.review,
    }),
  );
  report.push({
    path: pdf.path,
    outcome: "proposed work",
    title,
    titleFrom,
    authors,
  });
  process.stdout.write(".");
}
process.stdout.write("\n");

// Files inside zips (S7): each PDF with a text layer and each Word document
// becomes a work; the zip's proposal targets all of them. Pictures beside a
// PDF are its illustrations; scans wait for OCR; other formats are listed.
const zipReport: {
  path: string;
  entry?: string;
  outcome: string;
  title?: string;
  titleFrom?: string;
}[] = [];
for (const zip of inventory.zips) {
  const document = byPath.get(zip.path);
  if (!document) throw new Error(`Zip missing from the map: ${zip.path}`);
  const proposal = map.proposals.find(
    (p) => p.id === `proposal-${document.id}`,
  );
  if (!proposal) throw new Error(`No proposal for ${zip.path}`);
  if (proposal.review.by === "owner" || proposal.action !== "attachment") {
    zipReport.push({ path: zip.path, outcome: `kept (${proposal.action})` });
    continue;
  }
  const readable: { name: string }[] = [];
  for (const file of zip.files ?? []) {
    const outcome = /\.pdf$/i.test(file.name)
      ? file.kind === "text"
        ? undefined
        : "scan: OCR pending"
      : /\.doc$/i.test(file.name)
        ? undefined
        : /\.(?:jpe?g|png|gif)$/i.test(file.name)
          ? "illustration of the PDF beside it"
          : "not read: presentation or spreadsheet, kept in the archive";
    if (outcome) zipReport.push({ path: zip.path, entry: file.name, outcome });
    else readable.push(file);
  }
  const entryCatalog = catalog.get(urlKey(document.url));
  const targets: EditorialItem[] = [];
  for (const file of readable) {
    const source = {
      documentId: document.id,
      url: document.url,
      ...(document.timestamp ? { timestamp: document.timestamp } : {}),
      selection: { kind: "whole" as const },
      entry: file.name,
    };
    const edition = await attachmentEdition(source, map);
    if (!edition) throw new Error(`Unreadable entry ${file.name}`);
    const body = plain(edition.html);
    const heading = redact(load(edition.html)("h2,h3").first().text());
    const filename = (file.name.split("/").pop() ?? "")
      .replace(/\.(?:pdf|doc)$/i, "")
      .replace(/[_\s]+/g, " ")
      .trim();
    // The files' own metadata titles are unreliable (template names, the
    // author, "x.rtf"). One readable file: the catalog, the citing link or
    // the file name; several: each file's first heading, else its name.
    const single = readable.length === 1;
    const { linkText, duplicate } = single
      ? await referrers(document, zip.linkedFrom, body)
      : { linkText: undefined, duplicate: undefined };
    if (duplicate) {
      zipReport.push({
        path: zip.path,
        entry: file.name,
        outcome: `download copy of a page: ${duplicate.path}`,
      });
      continue;
    }
    const checked = ZIP_TITLES[`${zip.path}::${file.name}`];
    const [rawTitle, titleFrom] = checked
      ? [checked, "text"]
      : entryCatalog && single
        ? [redact(entryCatalog.title), "catalog"]
        : linkText
          ? [linkText, "link"]
          : // A name without lower case ("DRAGHI2") says little: the
            // file's first heading then names it.
            !single &&
              !/\p{Ll}/u.test(filename) &&
              usable(heading) &&
              heading.length <= 120
            ? [heading, "heading"]
            : [filename, "file"];
    const cased = checked ?? sentenceCase(rawTitle, body);
    const title = cased.charAt(0).toLocaleUpperCase("it") + cased.slice(1);
    const authors = (entryCatalog?.authors ?? [])
      .map((name) => redact(name))
      .filter((name) => name && name !== "[email removed]");
    for (const name of authors) {
      const id = authorId(name);
      if (!authorDocs.has(id)) authorDocs.set(id, { name, docs: new Set() });
      authorDocs.get(id)?.docs.add(document.id);
    }
    const quote = body.slice(0, 220);
    const selector = `zip:${file.name}`;
    const item: EditorialItem = {
      id: itemId(document.url, selector),
      slug: itemSlug(title, document.url, selector),
      title,
      level: "work",
      authors: authors.map(authorId),
      language: language(body),
      sources: [source],
      classification: unknownClassification(quote),
      contributions: [],
      developedIn: [],
      composition: "single",
      review: proposed(
        `A ${/\.doc$/i.test(file.name) ? "Word document" : "PDF with a text layer"} inside a recovered zip, read as text like the HTML works (S7); title from the ${titleFrom === "catalog" ? "original works catalog" : titleFrom === "link" ? "link that cites it" : titleFrom === "heading" ? "file's first heading" : titleFrom === "text" ? "file, checked by hand" : "file name"}.`,
        quote,
      ),
    };
    targets.push(item);
    zipReport.push({
      path: zip.path,
      entry: file.name,
      outcome: "proposed work",
      title,
      titleFrom,
    });
  }
  if (!targets.length) continue;
  newItems.push(...targets);
  lines[lineOf.get(proposal.id) ?? -1] = lines[
    lineOf.get(proposal.id) ?? -1
  ].replace(
    /\{.*\}/,
    JSON.stringify({
      id: proposal.id,
      documents: proposal.documents,
      action: "work",
      level: "work",
      targets: targets.map((t) => t.id),
      review: proposed(
        `A recovered zip whose ${targets.length === 1 ? "file is" : `${targets.length} files are`} read as text (S7).`,
        targets.map((t) => t.title).join(" · "),
      ),
    }),
  );
  process.stdout.write(":");
}
process.stdout.write("\n");

// Authors: extend an existing entry's documents, or add a new one.
const newAuthors: string[] = [];
for (const [id, { name, docs }] of authorDocs) {
  const at = lineOf.get(id);
  if (at !== undefined) {
    const author = JSON.parse(lines[at].trim().replace(/,$/, ""));
    author.documents = [...new Set([...author.documents, ...docs])];
    lines[at] = lines[at].replace(/\{.*\}/, JSON.stringify(author));
  } else
    newAuthors.push(
      JSON.stringify({
        id,
        name,
        review: proposed(
          "A name/pseudonym from the original works catalog entry that links this attachment; no identity or alias equivalence is inferred.",
          name,
        ),
        documents: [...docs],
      }),
    );
}
const insertAfter = (last: string, rows: string[]) => {
  const index = lines.findIndex(
    (_l, i) => lines[i] === last && lines[i + 1]?.trim().startsWith("]"),
  );
  if (index < 0) throw new Error("Section end not found");
  if (!rows.length) return;
  lines[index] = `${lines[index]},`;
  lines.splice(
    index + 1,
    0,
    ...rows.map((r, i) => `    ${r}${i < rows.length - 1 ? "," : ""}`),
  );
};
const lastOf = (section: string) => {
  const start = lines.findIndex((l) => l.startsWith(`  "${section}": [`));
  let i = start + 1;
  while (!lines[i + 1].trim().startsWith("]")) i++;
  return lines[i];
};
insertAfter(lastOf("authors"), newAuthors);
insertAfter(
  lastOf("items"),
  newItems.map((item) => JSON.stringify(item)),
);
const next = lines.join("\n");
// The edited map must still parse and validate before it is written.
mapSchema.parse(JSON.parse(next));
await writeFile("data/map.yaml", next);
if (!zipsOnly)
  await writeJson("reports/attachments-proposals.json", {
    date: new Date().toISOString().slice(0, 10),
    proposed: report.filter((r) => r.outcome === "proposed work").length,
    downloadCopies: report.filter((r) => r.outcome.startsWith("download"))
      .length,
    scans: report.filter((r) => r.outcome.startsWith("scan")).length,
    newAuthors: newAuthors.length,
    pdfs: report,
  });
const count = (prefix: string) =>
  zipReport.filter((r) => r.outcome.startsWith(prefix)).length;
await writeJson("reports/attachments-zip-proposals.json", {
  date: new Date().toISOString().slice(0, 10),
  proposed: count("proposed work"),
  scans: count("scan"),
  illustrations: count("illustration"),
  notRead: count("not read"),
  files: zipReport,
});
console.log(
  `${newItems.length} work proposals, ${newAuthors.length} new author names; reports in reports/attachments-*proposals.json`,
);
